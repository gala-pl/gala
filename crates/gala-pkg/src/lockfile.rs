//! `gala.lock` lockfile: deterministic serialization and parsing.

use std::collections::BTreeSet;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::error::{io_at, PkgError, Result};

/// File name of the lockfile inside a project directory.
pub const LOCKFILE_NAME: &str = "gala.lock";

/// Current lockfile format version.
pub const LOCK_FORMAT_VERSION: u32 = 1;

const HEADER: &str = "# This file is generated by gala-pkg. Do not edit by hand.\n";

/// A `gala.lock` file.
///
/// Packages are always kept sorted by name and each dependency list is sorted, so
/// [`Lockfile::to_toml_string`] is byte-identical for identical contents.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct Lockfile {
    /// Format version; must be [`LOCK_FORMAT_VERSION`].
    pub version: u32,
    /// Locked packages.
    #[serde(rename = "package", default, skip_serializing_if = "Vec::is_empty")]
    pub packages: Vec<LockedPackage>,
}

/// One locked package.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    /// Package name.
    pub name: String,
    /// Exact resolved version.
    pub version: String,
    /// Where the package came from: `registry`, `path+<dir>` or `git+<url>[#<rev>]`.
    pub source: String,
    /// SHA-256 of the package contents (registry packages only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub checksum: Option<String>,
    /// Names of the packages this one depends on, sorted.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
}

impl Lockfile {
    /// Create an empty lockfile at the current format version.
    pub fn new(mut packages: Vec<LockedPackage>) -> Self {
        for p in &mut packages {
            p.dependencies.sort();
            p.dependencies.dedup();
        }
        packages.sort_by(|a, b| a.name.cmp(&b.name));
        Self { version: LOCK_FORMAT_VERSION, packages }
    }

    /// Parse lockfile text.
    ///
    /// # Errors
    ///
    /// Returns [`PkgError::Lockfile`] for malformed TOML, an unsupported format version, or
    /// duplicate package names.
    pub fn parse(content: &str) -> Result<Self> {
        let lock: Self = toml::from_str(content).map_err(|e| PkgError::Lockfile(e.to_string()))?;
        if lock.version != LOCK_FORMAT_VERSION {
            return Err(PkgError::Lockfile(format!(
                "unsupported lockfile version {} (expected {LOCK_FORMAT_VERSION})",
                lock.version
            )));
        }
        let mut seen = BTreeSet::new();
        for p in &lock.packages {
            if !seen.insert(p.name.as_str()) {
                return Err(PkgError::Lockfile(format!("duplicate package `{}`", p.name)));
            }
        }
        Ok(Self::new(lock.packages))
    }

    /// Serialize to canonical TOML text, with packages and dependencies sorted.
    pub fn to_toml_string(&self) -> String {
        let canonical = Self::new(self.packages.clone());
        // Serializing plain strings and vectors cannot fail; fall back to the header alone
        // rather than panicking if that invariant were ever violated.
        let body = toml::to_string_pretty(&canonical).unwrap_or_default();
        format!("{HEADER}{body}")
    }

    /// Look up a locked package by name.
    pub fn get(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Read the lockfile at `path`, returning `None` if it does not exist.
    ///
    /// # Errors
    ///
    /// Returns I/O errors other than "not found", or parse errors.
    pub fn load(path: &Path) -> Result<Option<Self>> {
        match std::fs::read_to_string(path) {
            Ok(content) => Self::parse(&content).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(io_at(path)(e)),
        }
    }

    /// Write the canonical text to `path`.
    ///
    /// # Errors
    ///
    /// Returns I/O errors.
    pub fn write(&self, path: &Path) -> Result<()> {
        std::fs::write(path, self.to_toml_string()).map_err(io_at(path))
    }
}
